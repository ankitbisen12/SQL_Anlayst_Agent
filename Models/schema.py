from operator import add
from typing import Annotated, Literal

from pydantic import BaseModel, Field


class AgentState(BaseModel):
    messages: Annotated[list, add] = Field(default_factory=list, description='List of messages to be processed by the agent')   # this the prompt given by the user.
    user_question: str = Field(..., description="The original Question asked by the user")
    history: list[dict] = Field(default_factory=list, description="Previous turns of the conversation ({role, content}) used to resolve follow-up questions.")
    intent: str = Field(default="", description="Intent detected by the guardrails / classifier (data_question, modify_request, sensitive_request, ...).")
    curated_que: str = Field(default="", description="Curated question to be answered by the agent.")                # currated question given by the LLM model after restructuring the user message.
    prompt_context_query: str = Field(default="", description="Context for the prompt query")
    is_safe: Literal["Yes", "No"] = Field(default="No", description="Indicates whether the query generated by LLM is safe to perform against the database is safe or not.")
    generated_sql_query: str = Field(default="", description="The SQL query generated by the agent based on the cuarted question and prompt context")
    sql_query_execution_result: dict = Field(default_factory=dict, description="The result of executing the generated SQL query on the database ({columns, rows, row_count, truncated}).")
    sql_error: str = Field(default="", description="Database error of the last execution attempt, fed back to the LLM for self-correction.")
    attempts: int = Field(default=0, description="Number of SQL generation attempts made so far.")
    chart: dict = Field(default_factory=dict, description="Visualization spec chosen for the result.")
    final_answer: str = Field(default="", description="The final answer generated by the agent based on prompt.")
    comments: str = Field(default="", description="Additional Comments or feedback provided by the agent regarding the safety of the query generated by LLM.")


class judgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(..., description="Indicates whether the query generated by LLM is safe to perform against the database is safe or not.")
    comments: str = Field(..., description="Additional Comments or feedback provided by the agent regarding the safety of the query generated by LLM.")


class curationSchema(BaseModel):
    intent: Literal["data_question", "modify_request", "sensitive_request", "off_topic"] = Field(..., description="What the user is trying to do.")
    curated_question: str = Field(..., description="A clear, standalone version of the user's question (follow-ups resolved using the conversation history).")


class sqlGenerationSchema(BaseModel):
    answerable: bool = Field(..., description="False if the question cannot be answered with the available tables and columns.")
    sql: str = Field(..., description="A single PostgreSQL SELECT query, or an empty string when not answerable.")
    reason: str = Field(..., description="One short sentence: what the query does, or why the question is not answerable.")
